        Console.WriteLine("Exported public interop test vector.");
    }

    public static void VerifyFixture()
    {
        var values = Load();
        using var device = ECDsa.Create(Parameters(Hex(values["device.public"])));
        foreach (var name in new[] { "request", "receipt", "applied" })
        {
            var frame = RelayCanonicalEncoding.DecodeRelayFrame(Hex(values[name + ".frame"]));
            var aad = RelayCanonicalEncoding.EncodeRelayFrameAssociatedData(frame);
            var plaintext = RelayCryptography.Decrypt(Hex(values["recipient.private"]), Hex(values["recipient.public"]),
                frame.GetEncapsulatedKeyCopy(), frame.GetCiphertextCopy(), aad, Info(frame.Kind, aad));
            Require(plaintext.SequenceEqual(Hex(values[name + ".plaintext"])));
            if (name == "request")
            {
                var signed = RelayCanonicalEncoding.DecodeDeviceRequestEnvelope(plaintext);
                Require(device.VerifyHash(RelayCanonicalEncoding.ComputeDeviceRequestHash(signed), signed.GetSignatureP1363Copy()));
            }
            else
            {
                var signed = RelayCanonicalEncoding.DecodeDeviceReceiptEnvelope(plaintext);
                Require(device.VerifyHash(RelayCanonicalEncoding.ComputeDeviceReceiptHash(signed), signed.GetSignatureP1363Copy()));
            }
        }
    }

    public static void VerifyAndroid(string path)
    {
        var values = Load();
        var approval = RelayCanonicalEncoding.DecodeApprovalEnvelope(Hex(File.ReadAllText(path).Trim()));
        using var parent = ECDsa.Create(Parameters(Hex(values["recipient.public"])));
        Require(parent.VerifyHash(RelayCanonicalEncoding.ComputeApprovalHash(approval), approval.GetSignatureP1363Copy()));
        Require(RelayCanonicalEncoding.EncodeApprovalForSignature(approval).SequenceEqual(Hex(values["approval.input"])));
        Console.WriteLine("PASS Android approval signature and exact request binding verified by .NET.");
    }

    private static byte[] Seal(RelayFrameKind kind, byte[] plaintext, long cursor)
    {
        RelayFrame Frame(byte[] enc, byte[] cipher) => new(kind, "mailbox-alpha-0001", "recipient-key-0001", "frame-alpha-00000" + cursor,
            cursor, 0, Now.AddMinutes(-1), Now.AddHours(1), enc, cipher);
        var aad = RelayCanonicalEncoding.EncodeRelayFrameAssociatedData(Frame(Array.Empty<byte>(), Array.Empty<byte>()));
        var ciphertext = RelayCryptography.Encrypt(Hex(RecipientPublic), plaintext, aad, Info(kind, aad), out var encapsulated);
        return RelayCanonicalEncoding.EncodeRelayFrame(Frame(encapsulated, ciphertext));
    }

    private static byte[] Info(RelayFrameKind kind, byte[] aad) => Encoding.ASCII.GetBytes(kind == RelayFrameKind.Request
        ? "guard-relay-request-hpke-v1" : "guard-relay-receipt-hpke-v1").Concat(aad).ToArray();
    private static Dictionary<string, string> Load() => File.ReadAllLines(Path.Combine(AppContext.BaseDirectory, "relay-exchange-v1.properties"))
        .Where(x => !string.IsNullOrWhiteSpace(x) && !x.StartsWith('#')).Select(x => x.Split('=', 2)).ToDictionary(x => x[0], x => x[1]);
    private static byte[] Hex(string value) => Convert.FromHexString(value);
    private static ECParameters Parameters(byte[] key, byte[]? d = null) => new() { Curve = ECCurve.NamedCurves.nistP256,
        Q = new ECPoint { X = key[1..33], Y = key[33..65] }, D = d };
    private static byte[] Serialize(ECPoint point) => new byte[] { 4 }.Concat(point.X!).Concat(point.Y!).ToArray();
    private static void Require(bool condition) { if (!condition) throw new InvalidOperationException("Interop mismatch."); }
}
